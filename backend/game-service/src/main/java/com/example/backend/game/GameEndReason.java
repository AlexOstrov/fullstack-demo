package com.example.backend.game;

/**
 * Причина завершения партии (ТЗ 4.7, колонка {@code end_reason} таблицы {@code tournament}).
 * Устанавливается движком в момент перехода статуса в терминальный.
 */
public enum GameEndReason {
    /** У стороны, чей ход, нет допустимых ходов (ТЗ 3.6). */
    NO_MOVES,
    /** Сдача (ТЗ 3.6). */
    RESIGN,
    /** Троекратное повторение позиции (ТЗ 3.6). */
    DRAW_REPETITION,
    /** 15 ходов каждого игрока только дамками без взятий (ТЗ 3.6). */
    DRAW_KINGS,
    /** Ничья по согласию сторон (ТЗ 3.6). */
    DRAW_AGREEMENT
}
